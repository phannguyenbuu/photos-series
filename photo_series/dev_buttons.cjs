const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto('http://127.0.0.1:5174/?domain=dir&view=photo-series&photo_job=downloads-remote-smoke', { waitUntil: 'domcontentloaded' });
  const deploy = page.getByRole('button', { name: 'Deploy', exact: true });
  await deploy.waitFor({ state: 'visible', timeout: 20000 });
  const download = page.getByRole('link', { name: 'Tải Agent mới', exact: true });
  assert.equal(await download.getAttribute('href'), 'https://download.goxprint.com/printagentinstall.exe');
  const started = page.waitForResponse(response => response.url().endsWith('/__dev/dir-deploy') && response.request().method() === 'POST');
  await deploy.click();
  assert.equal((await started).status(), 202);
  await page.getByRole('status').filter({ hasText: 'Deploy thành công' }).waitFor({ timeout: 120000 });
  const job = await (await page.request.get('http://127.0.0.1:5174/__dev/dir-deploy')).json();
  assert.equal(job.status, 'completed', job.logs);
  await page.screenshot({ path: path.resolve('output/dir-dev-deploy.png'), fullPage: true });
  const production = await browser.newPage({ viewport: { width: 1083, height: 809 } });
  await production.goto('https://dir.toolxprint.com/?view=photo-series&photo_job=downloads-remote-smoke', { waitUntil: 'domcontentloaded' });
  await production.getByRole('link', { name: 'Tải Agent mới', exact: true }).waitFor({ timeout: 20000 });
  assert.equal(await production.getByRole('button', { name: 'Deploy', exact: true }).count(), 0);
  const head = await production.request.head('https://download.goxprint.com/printagentinstall.exe');
  assert.equal(head.status(), 200);
  assert.ok(head.headers()['content-disposition'].includes('attachment'));
  const assets = 'D:/Dropbox/_Documents/Goxprint/auto-gox-react/dist/assets';
  for (const name of fs.readdirSync(assets).filter(name => name.endsWith('.js'))) assert.equal(fs.readFileSync(path.join(assets, name), 'utf8').includes('/__dev/dir-deploy'), false, `Dev endpoint leaked into ${name}`);
  await production.screenshot({ path: path.resolve('output/dir-download-button.png'), fullPage: true });
  console.log(JSON.stringify({ devButton: 'visible and deployed successfully', productionDeployButton: 'absent', downloadButton: 'visible', installerHTTPS: head.status(), productionDevCode: 'absent' }));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
